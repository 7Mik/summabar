export function getSystemLang(): SupportedLang {
  const navLang = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2).toLowerCase() : 'it';
  if (navLang in TRANSLATIONS) {
    return navLang as SupportedLang;
  }
  return 'en';
}

export function t(key: string, lang?: string, params?: Record<string, string>): string {
  const currentLang = (lang && lang in TRANSLATIONS ? lang : getSystemLang()) as SupportedLang;
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;

  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), pVal);
    }
  }

  return text;
}
